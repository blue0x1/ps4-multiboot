"""Render anti-aliased ASCII glyphs into a C header for the installer.

  tools/gen-font.py OUT.h

Fonts: Noto Sans (SIL Open Font License 1.1). Each font becomes an array of
glyphs (32..126) with 8-bit alpha bitmaps, so the installer needs no font
library at boot.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

NOTO = "/usr/share/fonts/truetype/noto/"
FONTS = [
    ("font_small", NOTO + "NotoSans-Regular.ttf", 20),
    ("font_body", NOTO + "NotoSans-Regular.ttf", 26),
    ("font_bold", NOTO + "NotoSans-SemiBold.ttf", 26),
    ("font_title", NOTO + "NotoSans-SemiBold.ttf", 40),
]

out = ["/* Copyright (C) 2026 Chokri Hammedi (blue0x1) <https://github.com/blue0x1> */",
       "/* Generated by tools/gen-font.py from Noto Sans (SIL OFL 1.1). Do not edit. */",
       "#include <stdint.h>",
       "struct glyph { int16_t w, h, xoff, yoff, adv; uint32_t off; };",
       "struct font { int ascent, height; const struct glyph *g; const uint8_t *data; };"]

for name, path, size in FONTS:
    f = ImageFont.truetype(path, size)
    ascent, descent = f.getmetrics()
    glyphs, data = [], bytearray()
    for c in range(32, 127):
        ch = chr(c)
        adv = round(f.getlength(ch))
        box = f.getbbox(ch)  # relative to the top of the ascent line
        w, h = max(box[2] - box[0], 0), max(box[3] - box[1], 0)
        off = len(data)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=f, fill=255)
            data += im.tobytes()
        glyphs.append((w, h, box[0], box[1], adv, off))
    out.append(f"static const uint8_t {name}_data[] = {{")
    for i in range(0, len(data), 24):
        out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const struct glyph {name}_g[95] = {{")
    for g in glyphs:
        out.append("  {%d,%d,%d,%d,%d,%d}," % g)
    out.append("};")
    out.append(f"static const struct font {name} = {{ {ascent}, {ascent + descent}, {name}_g, {name}_data }};")

open(sys.argv[1], "w").write("\n".join(out) + "\n")
